#ifndef __MIN_MAX_H__
#define __MIN_MAX_H__

#include <stddef.h>

/**
 * Returns the maximum of a and b (int version).
 */
int max_int(int a, int b);
/**
 * Returns the minimum of a and b (int version).
 */
int min_int(int a, int b);
/**
 * Returns the maximum of a and b (size_t version).
 */
size_t max_size_t(size_t a, size_t b);
/**
 * Returns the minimum of a and b (size_t version).
 */
size_t min_size_t(size_t a, size_t b);


#endif
